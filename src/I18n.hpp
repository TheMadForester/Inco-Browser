inline QString& currentLang() {
    static QString lang = "en";
    return lang;
}

inline void setLanguage(const QString& code) {
    QString c = code.toLower();
    if (c == "system" || c.isEmpty()) {
        const auto sys = QLocale::system().name().toLower();
        if (sys.startsWith("de")) c = "de";
        else if (sys.startsWith("fr")) c = "fr";
        else if (sys.startsWith("it")) c = "it";
        else if (sys.startsWith("zh")) c = "zh";
        else c = "en";
    }
    if (c != "en" && c != "de" && c != "fr" && c != "it" && c != "zh")
        c = "en";
    currentLang() = c;

    // Qt's own strings (OK/Cancel/Yes/No in message boxes and input
    // dialogs) come from the qtbase catalogs shipped with Qt.
    if (auto* app = QCoreApplication::instance()) {
        static QTranslator* qt = nullptr;
        if (qt) {
            app->removeTranslator(qt);
            delete qt;
            qt = nullptr;
        }
        if (c != "en") {
            auto* t = new QTranslator(app);
            const QString name = c == "zh" ? QStringLiteral("qtbase_zh_CN") : QStringLiteral("qtbase_") + c;
            if (t->load(name, QLibraryInfo::path(QLibraryInfo::TranslationsPath))) {
                app->installTranslator(t);
                qt = t;
            } else {
                delete t;
            }
        }
    }
}

